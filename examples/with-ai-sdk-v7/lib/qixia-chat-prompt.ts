/** 地图选中地点时，随用户消息一起注入给模型的上下文说明（用户看不到）。 */
export function formatPlaceContext(place: {
  name: string;
  referenceCode?: string;
  address?: string;
  lng: number;
  lat: number;
  poiId?: string;
}): string {
  const meta = [
    place.address ? `高德地址：${place.address}` : "",
    `GCJ-02 坐标 ${place.lng},${place.lat}`,
    place.poiId ? `POI ${place.poiId}` : "",
  ]
    .filter(Boolean)
    .join("；");
  return [
    `[地图选中] 用户在地图上选中了地点「${place.name}」（${meta}）。`,
    "这是地图上的标点，不是用户的当前位置，也不代表用户已经到访。",
    place.referenceCode
      ? `查这处地点的资料时调用 get_qixia_knowledge，query 填「${place.referenceCode}」。`
      : "",
    "介绍这处地点时直接使用上面的名称与地址，不必再搜索同一个地点；只有用户问步行路线、周边配套或交通时才调用高德工具。",
  ].join("");
}
