// 定稿层：生成数据只当素材，这里记录「已经拍板的说法」与「暂时不对外给数字的字段」。
// 对话回答只读这一层（见 answer-view.ts），原始多来源并列仍保留给知识卡片展示。
// 新增结论时写清依据留在 basis 里，供维护者复核，不进入对话。

export type EditorialFact = {
  /** 对应 QixiaFact.key，同名字段以这里为准。 */
  key: string;
  /** 面向游客的说法，已是完整短语，不带来源与可信度。 */
  value: string;
  /** 为什么采用这个说法，只给维护者看。 */
  basis?: string;
};

export type EditorialEntry = {
  /** 一句话介绍，替代生成数据里模板化的 summary。 */
  intro?: string;
  facts?: readonly EditorialFact[];
  /** 从回答中移除的原始字段，避免与定稿字段重复或过于琐碎。 */
  hide?: readonly string[];
  /** 明确没有定论的字段：note 给对话用，detail 给维护者看。 */
  open?: readonly { field: string; note: string; detail?: string }[];
  /** 有定稿大事记时整段替换，避免与定稿年代互相打架。 */
  timeline?: readonly { date: string; what: string }[];
};

/** 来源域名 → 游客能看懂的口径。顺序有意义，先匹配先生效。 */
const SOURCE_LABELS: readonly (readonly [RegExp, string])[] = [
  [/qixia-guided-tour/, "景区导览资料"],
  [/qixia-miniprogram/, "景区小程序"],
  [/shanshanzhi-1790/, "《摄山志》"],
  [/qixiajianzhi-1999/, "《栖霞区志》"],
  [/qixiaxinzhi-1934/, "《栖霞新志》"],
  [/qixiawenshi-2000/, "《栖霞文史》"],
  [/zh\.wikipedia\.org/, "维基百科"],
  [/yzwb\.net/, "扬子晚报"],
  [/maigoo\.com/, "旅游资讯网站"],
  [/qixia\.winnielyu\.com/, "栖霞知识库"],
];

export function sourceLabel(url: string): string {
  for (const [pattern, label] of SOURCE_LABELS) {
    if (pattern.test(url)) return label;
  }
  return "网络资料";
}

