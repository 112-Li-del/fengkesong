export type EditorialFact = {
  /** 面向游客的项目名，如「位置」「看点」。 */
  key: string;
  /** 面向游客的说法，已是完整短语，不带来源与可信度。 */
  value: string;
  status?: "approved" | "pending";
  /** 为什么采用这个说法，只给维护者看。 */
  basis?: string;
};

export type EditorialEntry = {
  /** 一句话介绍，替代生成数据里模板化或未审核的 summary。 */
  intro?: string;
  facts?: readonly EditorialFact[];
  /** 资料互相矛盾、等待拍板的项目名。 */
  open?: readonly string[];
  timeline?: readonly {
    date: string;
    what: string;
    status?: "approved" | "pending";
  }[];
  /** 只用于检索、不作为「又名」展示的名称：误写、相邻景点名、未核实的对应关系。 */
  searchOnly?: readonly string[];
  aliases?: readonly string[];
};

