export function sourceLabel(source: string): string {
  for (const [pattern, label] of SOURCE_LABELS) {
    if (pattern.test(source)) return label;
  }
  if (!/^https?:\/\//.test(source)) {
    return source.replace(/（[^）]*参赛阅读[^）]*）/g, "").trim();
  }
  return "网络资料";
}

